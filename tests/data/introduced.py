"""Generate src/parse/introduced.rs: the elements and attributes OpenDRIVE
1.8 and 1.9 introduced, by path from <OpenDRIVE>, from the 1.9 XSD and the
spec's revision history annexes. Needs target/asam/ (see ROADMAP.md).

    uv run tests/data/introduced.py
"""
import glob, re, subprocess, xml.etree.ElementTree as ET
from pathlib import Path

XS = '{http://www.w3.org/2001/XMLSchema}'
types, groups, root = {}, {}, None
if not glob.glob('target/asam/xsd/*.xsd'):
    raise SystemExit('needs the OpenDRIVE 1.9 schema in target/asam/xsd/ (see ROADMAP.md)')
for f in sorted(glob.glob('target/asam/xsd/*.xsd')):
    for c in ET.parse(f).getroot():
        if c.tag == XS + 'complexType': types[c.get('name')] = c
        elif c.tag == XS + 'group': groups[c.get('name')] = c
        elif c.tag == XS + 'element' and c.get('name') == 'OpenDRIVE': root = c

def children(ct):
    out = []
    def walk(n):
        for c in n:
            tag = c.tag.replace(XS, '')
            if tag == 'element':
                ts = [c.get('type')] + [a.get('type') for a in c.findall(XS + 'alternative')]
                out.append((c.get('name'), [t for t in ts if t]))
            elif tag == 'group' and c.get('ref'): walk(groups[c.get('ref')])
            elif tag in ('extension', 'restriction'):
                if c.get('base') in types: walk(types[c.get('base')])
                walk(c)
            elif tag in ('sequence', 'choice', 'all', 'complexContent', 'complexType'): walk(c)
    walk(ct)
    return out

paths = {}  # type -> [path]
alternatives = set()  # (type, path) reached by an xs:alternative
def visit(path, ct, seen):
    for name, ts in children(ct):
        p = path + [name]
        for t in ts:
            paths.setdefault(t, []).append(p)
            if t != ts[0]: alternatives.add((t, tuple(p)))
            if t in types and t not in seen: visit(p, types[t], seen | {t})
visit([], root.find(XS + 'complexType'), set())

rows = set()
for v in (8, 9):
    text = Path(f'target/asam/spec/16_annexes_revision_history_ASAM_OpenDRIVE_revision_history_V1-{v}-0.txt').read_text()
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    i = lines.index('Classes and attributes') if 'Classes and attributes' in lines else 0
    cls, attrs = None, False
    for l in lines[i:]:
        m = re.match(r'G\.\d+\.\d+\.\d+ (t_\w+)', l)
        if m: cls, attrs = m.group(1), False; continue
        if cls is None: continue
        if re.fullmatch(rf'Introduced:\s+1\.{v}\.0', l):
            for p in paths.get(cls, []):
                if (cls, tuple(p)) not in alternatives: rows.add((tuple(p), None, v))
            continue
        if l.startswith('Table') and 'attributes' in l: attrs = True; continue
        if l.startswith('Deprecated'): cls = None; continue
        if attrs and re.fullmatch(r'[a-zA-Z]+', l) and l not in ('Name', 'Introduced', 'Deprecated'):
            for p in paths.get(cls, []): rows.add((tuple(p), l, v))

elements = {(p, v) for p, a, v in rows if a is None}
def covered(p, v):
    return any(q == p[:len(q)] and w <= v for q, w in elements if len(q) < len(p))
rows = sorted(
    (r for r in rows
     if not covered(r[0], r[2]) and not (r[1] is not None and (r[0], r[2]) in elements)),
    key=lambda r: (r[0], r[1] or '', r[2]))
out = ['//! Generated by `tests/data/introduced.py` from the 1.9 XSD and the spec\'s', '//! revision history. Do not edit.', '',
       '/// Each element or attribute OpenDRIVE 1.8 or 1.9 introduced: its path of', '/// element names from below `<OpenDRIVE>`, the attribute or `None` for the',
       '/// element itself, and the minor version that introduced it.', 'pub(super) const INTRODUCED: &[(&[&str], Option<&str>, u32)] = &[']
for p, a, v in rows:
    out.append('    (&[' + ', '.join(f'"{x}"' for x in p) + '], ' + (f'Some("{a}")' if a else 'None') + f', {v}),')
out.append('];')
Path('src/parse/introduced.rs').write_text('\n'.join(out) + '\n')
subprocess.run(['rustfmt', '--edition', '2021', 'src/parse/introduced.rs'], check=True)
print(len(rows), 'rows')
